_classifier = None


async def get_classifier():
    """
    异步获取分类器单例

    使用 asyncio.run_in_executor 在线程池中初始化模型
    避免在 Uvicorn 主事件循环中同步加载模型，导致 WebSocket 卡住
    """
    global _classifier
    if _classifier is None:
        loop = asyncio.get_event_loop()
        # 在线程池中执行 PersonStatusClassifier.__init__()
        # 返回初始化好的实例
        _classifier = await loop.run_in_executor(None, PersonStatusClassifier)
    return _classifier


async def classify_intent(query: str) -> dict:
    """
    统一意图识别入口（人员态势 / 安防态势 / 食堂管理 / 车辆态势 / 信息发布 / 能源态势 / 会议管理 / 消防态势 / 设备态势 / 综合态势总览 / 设备查询 / 其他）

    :param query: 用户输入
    :return: {"intent": "person_status" | "security_status" | "canteen_status" | "vehicle_status" | "information_status" | "energy_status" | "meeting_status" | "emergency_fire" | "device_status" | "compositive_overview" | "device_query" | "other", "score": 相似度}
    """
    # 获取分类器单例
    # 第一次调用时会在线程池中加载模型
    classifier = await get_classifier()

    # 在线程池中执行 encode 和相似度计算
    loop = asyncio.get_event_loop()
    intent, score = await loop.run_in_executor(
        None,
        classifier.classify_top_intent,
        query
    )

    logger.info(
        f"[classify_intent] query={query}, intent={intent}, score={score:.4f}"
    )

    return {
        "intent": intent,
        "score": score
    }


